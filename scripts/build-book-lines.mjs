// Builds the bundled opening book from lichess-org/chess-openings (CC0).
// Run: node scripts/build-book-lines.mjs
import { writeFile } from 'node:fs/promises'
import { Chess } from 'chess.js'

const FILES = ['a', 'b', 'c', 'd', 'e']
const MAX_PLY = 10
const BASE = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master'
const OUT = new URL('../src/renderer/src/chess/bookLines.ts', import.meta.url)

const sequences = new Set()
let rows = 0

for (const file of FILES) {
  const response = await fetch(`${BASE}/${file}.tsv`)
  if (!response.ok) throw new Error(`${file}.tsv -> ${response.status}`)
  const text = await response.text()
  for (const row of text.split('\n').slice(1)) {
    if (!row.trim()) continue
    const pgn = row.split('\t')[2]
    if (!pgn) continue
    rows += 1

    const sanMoves = pgn.replace(/\{[^}]*\}/g, '').split(/\s+/).filter((token) => token && !/^\d+\.+$/.test(token) && !/^(1-0|0-1|1\/2-1\/2|\*)$/.test(token))
    const chess = new Chess()
    const prefix = []
    for (const san of sanMoves.slice(0, MAX_PLY)) {
      let move
      try {
        move = chess.move(san)
      } catch {
        break
      }
      prefix.push(`${move.from}${move.to}${move.promotion ?? ''}`)
      sequences.add(prefix.join(' '))
    }
  }
}

const sorted = [...sequences].sort()
const body = `// Generated by scripts/build-book-lines.mjs — do not edit.
// Opening sequences from lichess-org/chess-openings, dedicated to the public domain (CC0 1.0).
export const BOOK_MAX_PLY = ${MAX_PLY}
export const BOOK_LINES = new Set(\`${sorted.join('\n')}\`.split('\\n'))
`
await writeFile(OUT, body)
console.log(`rows=${rows} sequences=${sorted.length} bytes=${body.length}`)